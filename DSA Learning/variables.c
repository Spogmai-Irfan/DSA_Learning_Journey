#include <stdio.h>
int main(){
    int age =39;
    float height =5.7;
    char gender = 'M';
    double weight =70.55;
    printf("age:%d\n",age);
    printf("height:%.1f\n",height);
    printf("gender:%c\n",gender);
    printf("weight:%.2f\n",weight);
    return 0;
}